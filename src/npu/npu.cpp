// AMD XDNA2 NPU offload of PQ2_0 matrix-vector products for the CPU backend.
//
// Each weight in the NPU buffer is split row-wise: rows [0, Mn) are packed
// into NPU memory (npurun), rows [Mn, M) stay in CPU memory in the repack
// layout. A MUL_MAT launches the NPU part on a worker thread while all CPU
// threads compute their rows, so the two memory streams add up and the NPU
// launch latency is hidden behind CPU work.
//
// Weights that share one input (q/k/v, attn_qkv/attn_gate, ffn_gate/ffn_up)
// form a group: one NPU launch computes the NPU rows of every member and the
// later members' nodes read the cached result.
//
// Environment:
//   GGML_NPU=0              disable
//   GGML_NPU_XCLBIN=path    core program file (default: the copy embedded at build time)
//   GGML_NPU_SPLIT=f        fraction of rows on the NPU (default 0.75; 1.0 = NPU only)
//   GGML_NPU_LOCK=0         do not pin the CPU share of the weights in RAM
//   GGML_NPU_CPU_COPY=0|1   keep all rows on the CPU as well, so batches
//                           (prompt processing) run entirely on the CPU
//                           (default: 1 when the weights take < 4 GiB)
//   GGML_NPU_PMODE=mode     NPU power mode while running (default turbo)
//   GGML_NPU_STATS=1        print launch statistics at exit

